"""Running the proxy as a persistent systemd user service.

``web-ui install`` writes three units into ``$XDG_DATA_HOME/systemd/user``
(``~/.local/share/systemd/user``: searched by systemd like ``~/.config``, but
not usually under version control):

- ``web-ui-proxy.socket``: systemd holds ``front.sock`` and the loopback port.
  While the proxy restarts, new connections wait in the socket's queue
  instead of being refused, and the first connection starts the proxy.
- ``web-ui-proxy.service``: ``Type=notify``; the proxy takes its listening
  sockets from systemd (``LISTEN_FDS``) and says READY=1 once it serves.
- ``web-ui-tunnel@.service``: ``web-ui tunnel HOST`` kept up (enable it per
  host if you want tunnels from boot rather than on first visit).

Each file starts with :data:`MARK`; install and uninstall only touch those.
Instances started by the systemd runner are their own transient units, so a
proxy restart leaves them running.
"""

from __future__ import annotations

import logging
import os
import shlex
import socket
import subprocess
import time
from collections.abc import Callable
from pathlib import Path

from web_ui.config import Config, runtime_root

log = logging.getLogger(__name__)

MARK = "# Generated by web-ui install"
PROXY = "web-ui-proxy"
TUNNEL = "web-ui-tunnel@"
SD_LISTEN_FDS_START = 3


def unit_dir() -> Path:
    if p := os.environ.get("WEB_UI_UNIT_DIR"):
        return Path(p)
    base = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share")
    return base / "systemd" / "user"


def exec_line(argv: list[str]) -> str:
    """A command line for ExecStart=: quoted, with systemd's % and $ escaped."""
    return " ".join(shlex.quote(a).replace("%", "%%").replace("$", "$$") for a in argv)


def spec(path: Path) -> str:
    """``path`` for a unit file: under $XDG_RUNTIME_DIR as %t, under $HOME as %h."""
    p = str(path).replace("%", "%%")
    for base, s in ((str(runtime_root()), "%t"), (str(Path.home()), "%h")):
        if p == base or p.startswith(base + "/"):
            return s + p[len(base):]
    return p


def ipv6_loopback() -> bool:
    """Whether [::1] can be bound here (a socket unit fails outright if one address can't)."""
    if not socket.has_ipv6:
        return False
    try:
        with socket.socket(socket.AF_INET6, socket.SOCK_STREAM) as s:
            s.bind(("::1", 0))
    except OSError:
        return False
    return True


def units(cfg: Config, argv: list[str], tcp: bool = True, process_runner: bool = False) -> dict[str, str]:
    """The unit files to install: name -> text.  ``argv`` runs web-ui (see Ctx.web_ui_argv)."""
    head = f"{MARK}; `web-ui install` rewrites it, `web-ui uninstall` removes it.\n"
    listen = [f"ListenStream={spec(cfg.front_socket)}"]
    if tcp and cfg.port:
        listen.append(f"ListenStream=127.0.0.1:{cfg.port}")
        if ipv6_loopback():
            listen.append(f"ListenStream=[::1]:{cfg.port}")
    sock = (f"{head}\n[Unit]\nDescription=web-ui front door (front.sock{', loopback port' if tcp else ''})\n\n"
            "[Socket]\n" + "".join(f"{ln}\n" for ln in listen)
            + "SocketMode=0600\nDirectoryMode=0700\n"
            + f"Service={PROXY}.service\n\n[Install]\nWantedBy=sockets.target\n")  # fmt: skip
    # The process runner starts instances as children of the proxy, in its
    # cgroup; KillMode=process keeps them when the proxy restarts.
    kill = "KillMode=process\n" if process_runner else ""
    service = (f"{head}\n[Unit]\nDescription=web-ui front-door proxy\nRequires={PROXY}.socket\n"
               f"After={PROXY}.socket\n\n[Service]\nType=notify\n"
               f"ExecStart={exec_line([*argv, 'serve'])}\nExecReload=/bin/kill -HUP $MAINPID\n"
               f"Restart=on-failure\nRestartSec=5\n{kill}\n[Install]\nWantedBy=default.target\n")  # fmt: skip
    tunnel = (f"{head}\n[Unit]\nDescription=web-ui tunnel to %i\nAfter={PROXY}.service\n\n[Service]\n"
              f"ExecStart={exec_line([*argv, 'tunnel', '--batch'])} %i\n"
              "Restart=always\nRestartSec=15\n\n[Install]\nWantedBy=default.target\n")  # fmt: skip
    return {f"{PROXY}.socket": sock, f"{PROXY}.service": service, f"{TUNNEL}.service": tunnel}


def installed(root: Path | None = None) -> bool:
    """Whether `web-ui install` put the proxy's units here."""
    try:
        return (root or unit_dir()).joinpath(f"{PROXY}.service").read_text().startswith(MARK)
    except OSError:
        return False


def systemctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True, check=False)


def _transient(run: Callable[..., subprocess.CompletedProcess], unit: str) -> bool:
    """Whether ``unit`` is a transient unit (e.g. from `serve --detach` under the systemd runner)."""
    r = run("show", "-p", "Transient,ActiveState", "--", unit)
    props = dict(line.partition("=")[::2] for line in r.stdout.splitlines())
    return props.get("Transient") == "yes" and props.get("ActiveState") in ("active", "activating", "reloading")


def _stop_transient(run: Callable[..., subprocess.CompletedProcess], unit: str, wait: float = 10.0) -> None:
    """Stop ``unit`` and make systemd forget it.

    An older proxy can take its full TimeoutStopSec (90s) to exit, so after
    ``wait`` seconds it is killed.  Our socket, if an earlier install made it,
    is stopped too: while it listens, the next connection would start the
    transient unit again.  A transient unit stays loaded while failed, or
    while the socket names it, and its file under .../systemd/transient
    outranks ours even across daemon-reload; reset-failed and removing that
    file (systemd's own copy, written by systemd-run) let ours load.
    """
    fragment = run("show", "-p", "FragmentPath", "--value", "--", unit).stdout.strip()
    run("stop", "--no-block", "--", f"{PROXY}.socket", unit)
    deadline = time.monotonic() + wait
    while time.monotonic() < deadline and _state(run, unit) in ("active", "deactivating", "reloading"):
        time.sleep(0.2)
    if _state(run, unit) in ("active", "deactivating", "reloading"):
        log.warning("%s did not stop within %gs; killing it", unit, wait)
        run("kill", "--signal=SIGKILL", "--", unit)
        deadline = time.monotonic() + wait
        while time.monotonic() < deadline and _state(run, unit) not in ("inactive", "failed", ""):
            time.sleep(0.2)
    run("reset-failed", "--", unit)
    if "/systemd/transient/" in fragment:
        Path(fragment).unlink(missing_ok=True)


def _state(run: Callable[..., subprocess.CompletedProcess], unit: str) -> str:
    r = run("show", "-p", "ActiveState", "--value", "--", unit)
    return r.stdout.strip()


def install(cfg: Config, argv: list[str], tcp: bool = True, process_runner: bool = False,
            root: Path | None = None, run: Callable[..., subprocess.CompletedProcess] = systemctl) -> list[str]:  # fmt: skip
    """Write the units, take over from a transient proxy, enable and start them.  Idempotent.

    Returns what was done.  A running installed proxy whose unit changed is
    restarted, which (with the socket held by systemd) queues rather than
    refuses new connections.
    """
    root = root or unit_dir()
    root.mkdir(parents=True, exist_ok=True)
    done, changed = [], []
    for name, text in units(cfg, argv, tcp, process_runner).items():
        path = root / name
        try:
            old = path.read_text()
        except OSError:
            old = None
        if old == text:
            continue
        if old is not None and not old.startswith(MARK):
            raise RuntimeError(f"{path} exists and was not written by web-ui install; move it away first")
        path.write_text(text)
        changed.append(name)
        done.append(f"{'updated' if old else 'wrote'} {path}")
    if _transient(run, f"{PROXY}.service"):
        # A transient unit outranks unit files; it must go before ours can load.
        _stop_transient(run, f"{PROXY}.service")
        done.append(f"stopped the transient {PROXY}.service")
        changed.append(f"{PROXY}.service")
    if changed:
        _check(run("daemon-reload"), "daemon-reload")
    _check(run("enable", "--now", f"{PROXY}.socket"), f"enable {PROXY}.socket")
    _check(run("enable", f"{PROXY}.service"), f"enable {PROXY}.service")
    if f"{PROXY}.service" in changed or f"{PROXY}.socket" in changed:
        _check(run("restart", f"{PROXY}.service"), f"restart {PROXY}.service")
        done.append(f"(re)started {PROXY}.service")
    else:
        _check(run("start", f"{PROXY}.service"), f"start {PROXY}.service")
    return done


def uninstall(root: Path | None = None, run: Callable[..., subprocess.CompletedProcess] = systemctl) -> list[str]:
    """Stop and disable the proxy's units and remove the files install wrote."""
    root = root or unit_dir()
    run("disable", "--now", f"{PROXY}.socket", f"{PROXY}.service")
    done = []
    for name in (f"{PROXY}.socket", f"{PROXY}.service", f"{TUNNEL}.service"):
        path = root / name
        try:
            if path.read_text().startswith(MARK):
                path.unlink()
                done.append(f"removed {path}")
        except OSError:
            pass
    if done:
        run("daemon-reload")
    return done


def _check(r: subprocess.CompletedProcess, what: str) -> None:
    if r.returncode:
        raise RuntimeError(f"systemctl --user {what}: {(r.stderr or r.stdout).strip()}")


# ---- inside the service -------------------------------------------------------------


def listen_fds() -> list[socket.socket]:
    """The listening sockets systemd passed us (sd_listen_fds), and forget them in the environment."""
    try:
        mine = int(os.environ.get("LISTEN_PID", "")) == os.getpid()
        count = int(os.environ.get("LISTEN_FDS", "0")) if mine else 0
    except ValueError:
        count = 0
    for var in ("LISTEN_PID", "LISTEN_FDS", "LISTEN_FDNAMES"):
        os.environ.pop(var, None)  # children (instances) must not think they're activated
    socks = []
    for fd in range(SD_LISTEN_FDS_START, SD_LISTEN_FDS_START + count):
        os.set_inheritable(fd, False)
        socks.append(socket.socket(fileno=fd))
    return socks


def notify(state: str) -> bool:
    """sd_notify: tell systemd our state (READY=1, STOPPING=1, STATUS=...), if it is listening."""
    addr = os.environ.get("NOTIFY_SOCKET")
    if not addr:
        return False
    if addr.startswith("@"):
        addr = "\0" + addr[1:]
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_DGRAM) as s:
            s.sendto(state.encode(), addr)
    except OSError as e:
        log.warning("sd_notify %r: %s", state, e)
        return False
    return True
